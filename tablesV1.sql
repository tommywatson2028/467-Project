DROP TABLE IF EXISTS REQUESTS;
DROP TABLE IF EXISTS INVENTORY;
DROP TABLE IF EXISTS ORDERS;
DROP TABLE IF EXISTS EMPLOYEE;
DROP TABLE IF EXISTS PARTS;
DROP TABLE IF EXISTS BRACKETS;

CREATE TABLE PARTS (
    Num INT(11) NOT NULL,
    Description VARCHAR(50) NOT NULL,
    Price FLOAT(8,2) NOT NULL,
    Weight FLOAT(4,2) NOT NULL,
    PictureURL VARCHAR(50) NOT NULL,
    PRIMARY KEY (Num)
    );

CREATE TABLE ORDERS (
    TrackingID INT(4) AUTO_INCREMENT NOT NULL,
    Status VARCHAR(50) NOT NULL,
    Total DECIMAL(10,2) NOT NULL,
    Name VARCHAR(50) NOT NULL,
    CCNumber VARCHAR(16),
    City VARCHAR(50) NOT NULL,
    Street VARCHAR(50) NOT NULL,
    Contact VARCHAR(50) NOT NULL,
    PRIMARY KEY (TrackingID)
    );
 
CREATE TABLE EMPLOYEE (
    EmpID VARCHAR(11) NOT NULL,
    IsAdmin BOOLEAN NOT NULL DEFAULT FALSE,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    Username VARCHAR(50) NOT NULL,
    Password VARCHAR(50) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    PRIMARY KEY (EmpID)
    );

CREATE TABLE INVENTORY (
    Num INT(11) NOT NULL,
    InvQty INT NOT NULL,
    PRIMARY KEY (Num),
    FOREIGN KEY (Num) REFERENCES PARTS(Num) ON DELETE CASCADE
    );

CREATE TABLE REQUESTS (
    TrackingID INT(4) AUTO_INCREMENT NOT NULL, 
    Num INT(11) NOT NULL,
    OrderQty INT NOT NULL,
    PRIMARY KEY (TrackingID, Num),
    FOREIGN KEY (TrackingID) REFERENCES ORDERS(TrackingID) ON DELETE CASCADE,
    FOREIGN KEY (Num) REFERENCES PARTS(Num) ON DELETE CASCADE
    );

CREATE TABLE BRACKETS (
    BracketID INT AUTO_INCREMENT NOT NULL,
    MinWeight DECIMAL(8,2) NOT NULL,
    MaxWeight DECIMAL(8,2) NOT NULL,
    Charge DECIMAL(8,2) NOT NULL,
    PRIMARY KEY (BracketID)
    );

